const WaveThemePreset* find_wave_theme_preset(std::string_view name) noexcept {
    for (const auto& theme : kThemePresets) {
        if (theme.name == name) {
            return &theme;
        }
    }
    return nullptr;
}

const WaveThemePreset& default_wave_theme_preset() noexcept {
    return kThemePresets[0];
}

const WaveThemePreset& wave_theme_preset_or_default(std::string_view name) noexcept {
    if (const auto* found = find_wave_theme_preset(name)) {
        return *found;
    }
    return default_wave_theme_preset();
}

