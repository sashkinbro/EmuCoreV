#!/usr/bin/env python3
"""Regenerates yuv_shaders.inc (SPIR-V of the two compute shaders) with glslc.

usage: build_yuv_shaders.py [path/to/glslc]   (default: glslc from PATH or the newest Android NDK)
Debug/maintenance tool only, the .inc is committed and the build never runs this.
"""
import glob, os, shutil, struct, subprocess, sys, tempfile

here = os.path.dirname(os.path.abspath(__file__))
glslc = sys.argv[1] if len(sys.argv) > 1 else shutil.which('glslc')
if not glslc:
    cands = sorted(glob.glob(os.path.expanduser('~/AppData/Local/Android/Sdk/ndk/*/shader-tools/*/glslc*')))
    glslc = cands[-1] if cands else None
assert glslc, 'glslc not found'

out = ['// Generated by build_yuv_shaders.py (glslc --target-env=vulkan1.0 -O). Do not edit.\n']
for name, ident in (('yuv_convert_planar.comp', 'yuv_planar_spv'), ('yuv_convert_ycbcr.comp', 'yuv_ycbcr_spv')):
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, 'o.spv')
        subprocess.run([glslc, '--target-env=vulkan1.0', '-O', '-fshader-stage=compute', os.path.join(here, name), '-o', spv], check=True)
        data = open(spv, 'rb').read()
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    out.append('// %s\n' % name)
    out.append('static const uint32_t %s[] = {\n' % ident)
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',\n')
    out.append('};\n')
open(os.path.join(here, 'yuv_shaders.inc'), 'w', newline='\n').write(''.join(out))
print('wrote yuv_shaders.inc')
